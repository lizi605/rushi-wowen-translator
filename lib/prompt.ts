- 外层固定：以“如是我闻。一时，佛在舍卫城。尔时，须菩提从座而起，合掌白佛言：……”开篇，由须菩提请问，佛陀讲述和开示；不得让原文人物取代佛陀或须菩提。
- 开场固定而简短：不得改成“佛与须菩提共坐”“游化人间”“佛与大众俱”，也不得整段复制真实《金刚经》的发心、住心、降伏其心问答来充数。冒号后的第一问必须与原文相关。
- 内层固定：用户原文是佛陀所举的事例。保留原文人物、称谓、物品、动作、数量、时间、关键台词、事件次序和结局，不新增事实。
- 内层叙事与对白必须译成浅近文言和汉译佛经语气。保留关键台词的含义、对象和力度，但不得连续照抄现代口语；专名、数字和必要的现代名词可以保留。
- 常见现代社交词也应译古，例如按语境将“面子”化为“颜面、情面”，将“讲义气、重感情”化为“尚义重情”；不得只改“你”为“汝”便算完成。
- 把原文视为事实闭集：禁止补写原文没有的承诺、补偿规则、职业经历、精确台词、心理动机、旁人反应或后续结果。
