const plainLevelInstructions: Record<ZhouliLevel, string> = {
  light:
    "略释：只输出一句像评论区回复的话，通常30到70字，把原文真正意思直接说破；若原文只有单字或短句，可只用1到20字直接解释，不必凑字数；若原文是第一人称，就保留“我/我们”。",
  standard:
    "明释：输出2到3句，像网友把梗翻成人话一样自然解释；若原文只有单字或短句，可用一句短释，不必凑成多句；不要用“我其实是在说”这类开头，原文是第一人称时继续用“我/我们”。总长不超过180字。",
  grand:
    "详释：输出3到5句，可以分层但不要列报告标签；像认真网友在评论区多解释几句，原文只有单字或短句时仍以准确为先，不要为了变长而编故事。原文是第一人称时继续用第一人称。总长不超过320字。",
};

export function buildPlainPrompt(
  text: string,
  level: ZhouliLevel,
  plainMode: PlainMode,
) {
  const modeInstruction = plainModeInstructions[plainMode];

  if (!modeInstruction) {
    throw new Error(`Unsupported plain mode: ${String(plainMode)}`);
  }

  return `${modeInstruction}
${plainLevelInstructions[level]}

硬性要求：
- 若原文只是单字、双字词或很短的常见短句，例如“善”“善哉”“甚善”，直接释成“好”“可以”“很不错”这类现代意思即可；不必凑字数，不必硬写成段落。
- 不要继续写佛经体。
- 不要保留无意义的行脚僧故事、渡河譬喻、因果业缘包装。
- 不要把它总结成空泛大道理，要说清它在现代语境里到底想表达什么。
- 口吻要像网友顺手解释：短句、自然、有一点现场感，可以有一点吐槽；不要端着写成总结报告。
- 第一句直接进入释义，直接输出意思，不要先加解释框架或口头禅。
- 禁止以“这段话的意思是”“这句话是在说”“人话说就是”“翻译一下”“说白了”“简单说”“本质上是”“他其实”“作者其实”“我其实是在说”开头。
- 原文是第一人称，输出也必须直接用第一人称；不要改成“他/对方/作者其实想说”，也不要用旁观者口吻包一层。
- 不要输出报告式标签、小标题或课堂分析腔，不要用“我其实是在说”。
- 必须保留原文的关键对象、动作和立场，不能把解释改成反驳，不能把请求改成审判。
- 必须保留具体对象和对象关系：谁在评价谁、谁想回复谁、谁担心什么，不能省成一个模糊的“你/他/对方”。
- 不要虚构原文没有说的事实；不确定时只能说“可能是在……”或“像是在……”，不能说成确定事实。
- 如果原文是在问“怎么说、怎么回复、如何体面、委婉一点”，只解释它想表达的诉求和顾虑，不要继续代写回复。
- 如果原文是在求体面说法，解经必须保留“我是在求一句体面/委婉的说法”这个动作，不要把它压缩成对别人说“你应该怎样”。
- 如果原文提到“把某句话说得委婉/这话怎么回”，必须保留待处理句子的关键对象和评价，不要只剩“我在求一句体面话”。
- 如果原文是在拒绝威胁、侮辱、隐私泄露或自伤暗示，要保留温和拒绝、提醒求助、只谈事实和诉求等安全意图。
- 如果原文是在拉票、求赞、求投币，要直接翻出这个意图，但语气可以保留幽默。
- 如果原文是在阴阳怪气、反讽或对线，要翻出火药味，但不要升级攻击。
- 如果原文是在调侃某人或 @ 某人，解经要保留这种调侃和指向，不要改成“别慌/这很正常”式安慰。
- “说白了/翻译一下/绕半天”不要默认放在开头；能不用就不用，锐评也先直接说结论。
- 不要使用编号列表、加粗、项目符号或任何 Markdown；不要用序号分条。
- 输出只包含释义结果，不加标题，不使用 Markdown。

请把下面这段佛经体翻回正常人话：
<佛经体>
${text}
</佛经体>`;
}
